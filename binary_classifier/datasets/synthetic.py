"""Synthetic dataset of generalized-Gaussian-distributed RGB patches.

The synthetic data is generated by ``src/main_syn.py`` and stored as four
PyTorch tensor files inside the directory passed as ``root``::

    <root>/train_syn_data.pt
    <root>/train_syn_label.pt
    <root>/test_syn_data.pt
    <root>/test_syn_label.pt

This loader simply reads those files; it never touches global filesystem
paths. To (re)generate the tensors run::

    python src/main_syn.py --root <root>
"""

import logging
import os
import random

import numpy as np
import torch
from torch.utils.data import Dataset, Subset

from base.torchvision_dataset import TorchvisionDataset
from .preprocessing import create_semisupervised_setting


class Synthetic_Dataset(TorchvisionDataset):
    """Generalized-Gaussian noise patches used for the WACV 2022 synthetic experiment."""

    def __init__(self, root: str, normal_class: int = 0, known_outlier_class: int = 1,
                 n_known_outlier_classes: int = 0,
                 ratio_known_normal: float = 0.0, ratio_known_outlier: float = 0.0,
                 ratio_pollution: float = 0.0):
        super().__init__(root)
        logger = logging.getLogger()

        self.n_classes = 2
        self.normal_classes = tuple([normal_class])
        self.outlier_classes = list(range(0, 2))
        self.outlier_classes.remove(normal_class)
        self.outlier_classes = tuple(self.outlier_classes)

        if n_known_outlier_classes == 0:
            self.known_outlier_classes = ()
        elif n_known_outlier_classes == 1:
            self.known_outlier_classes = tuple([known_outlier_class])
        else:
            self.known_outlier_classes = tuple(
                random.sample(self.outlier_classes, n_known_outlier_classes))

        train_data_path = os.path.join(root, 'train_syn_data.pt')
        train_label_path = os.path.join(root, 'train_syn_label.pt')
        test_data_path = os.path.join(root, 'test_syn_data.pt')
        test_label_path = os.path.join(root, 'test_syn_label.pt')
        for p in (train_data_path, train_label_path, test_data_path, test_label_path):
            if not os.path.exists(p):
                raise FileNotFoundError(
                    f"Missing synthetic tensor file: {p}\n"
                    f"Generate it with: python src/main_syn.py --root {root}"
                )

        train_data = torch.load(train_data_path)
        train_label = torch.load(train_label_path)
        test_data = torch.load(test_data_path)
        test_label = torch.load(test_label_path)

        train_set = _TensorToDataset(train_data, train_label, train=True)
        logger.info("Synthetic train set length (raw): %d", len(train_set))

        idx, _, semi_targets = create_semisupervised_setting(
            np.asarray(train_set.targets), self.normal_classes, self.outlier_classes,
            self.known_outlier_classes, ratio_known_normal, ratio_known_outlier, ratio_pollution)
        train_set.semi_targets[idx] = torch.tensor(semi_targets)

        self.train_set = Subset(train_set, idx)
        self.test_set = _TensorToDataset(test_data, test_label, train=False)
        logger.info("Synthetic train set length (after semi-sup split): %d", len(self.train_set))
        logger.info("Synthetic test set length: %d", len(self.test_set))


class _TensorToDataset(Dataset):
    def __init__(self, tensor_batch, targets, train: bool = False):
        self.train = train
        self.tensor_batch = tensor_batch
        self.targets = targets
        self.semi_targets = torch.zeros_like(torch.tensor(self.targets))

    def __len__(self):
        return len(self.tensor_batch)

    def __getitem__(self, index):
        img = self.tensor_batch[index]
        target = self.targets[index]
        semi_target = int(self.semi_targets[index])
        return img, target, semi_target, index
